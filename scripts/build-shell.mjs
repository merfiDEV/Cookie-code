/**
 * Сборка shell.html из src/ui/shell/ (ESM)
 */
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SRC_DIR = path.join(ROOT, "src", "ui", "shell");
const OUT = path.join(ROOT, "src", "ui", "shell.html");

function readSrc(rel) {
  return fs.readFileSync(path.join(SRC_DIR, rel), "utf8");
}
function expandIncludes(html, depth = 0) {
  if (depth > 10) throw new Error("@include nested too deep");
  return html.replace(/<!--@include:([^>]+?)-->/g, (_, rel) =>
    expandIncludes(readSrc(rel.trim()), depth + 1),
  );
}
function expandCssIncludes(css, depth = 0) {
  if (depth > 10) throw new Error("CSS @include nested too deep");
  return css.replace(/\/\*@include:([^*]+?)\*\//g, (_, rel) =>
    expandCssIncludes(readSrc(rel.trim()), depth + 1),
  );
}

async function main() {
  let html = expandIncludes(readSrc("index.html"));
  html = html.replace(/\/\*@include:styles\/([^*]+?)\*\//g, (_, rel) =>
    expandCssIncludes(readSrc("styles/" + rel.trim())),
  );

  const result = await build({
    entryPoints: [path.join(SRC_DIR, "scripts", "main.ts")],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: "es2020",
    minify: false,
    legalComments: "none",
    logLevel: "warning",
    jsx: "automatic",
    jsxImportSource: "react",
    loader: { ".tsx": "tsx", ".ts": "ts" },
    define: { "process.env.NODE_ENV": '"production"' },
  });
  const js = result.outputFiles[0].text;

  if (!html.includes("//@bundle")) throw new Error("missing //@bundle");
  html = html.replace("//@bundle", () => js);

  const banner = "<!-- AUTO-GENERATED by scripts/build-shell.mjs -->\n";
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, banner + html, "utf8");
  console.log(
    "[build-shell] wrote",
    OUT,
    "(" + (banner.length + html.length) + " bytes)",
  );
}

main().catch((err) => {
  console.error("[build-shell] failed:", err);
  process.exit(1);
});
